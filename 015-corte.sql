-- FASE 8G-1: Empacadora/Corte (Informe General F.A.16 + Inspeccion F.A.14) + calendario de cintas
CREATE TABLE IF NOT EXISTS cintas_calendario (
  anio INTEGER NOT NULL,
  semana INTEGER NOT NULL,
  cinta_embolse INTEGER,
  cinta_embolse2 INTEGER,
  cinta_10sem INTEGER, cinta_11sem INTEGER, cinta_12sem INTEGER, cinta_13sem INTEGER, cinta_14sem INTEGER,
  lunes TEXT,
  PRIMARY KEY (anio, semana)
);

CREATE TABLE IF NOT EXISTS cortes (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  codigo TEXT NOT NULL UNIQUE,
  fecha TEXT NOT NULL,
  semana INTEGER,
  finca TEXT, cod_finca TEXT, destino TEXT, pdo TEXT, inspector TEXT,
  area_recorrida REAL, pct_recusados REAL, ratio_cortado REAL, ratio_procesado REAL,
  peso_prom REAL, calibracion_prom REAL, manos_prom REAL,
  largo_2da_mano REAL, largo_ult_mano REAL,
  merma_cortada REAL, merma_procesada REAL, dedos_caja INTEGER,
  prod_dole18 INTEGER, prod_13kg INTEGER, prod_single INTEGER, prod_otras INTEGER,
  cajas_recusadas INTEGER, cajas_embarcadas INTEGER, cajas_plantas INTEGER,
  hombres_campo INTEGER, hombres_planta INTEGER, hombres_empacando INTEGER,
  material_usado TEXT, horas_perdidas TEXT, observaciones TEXT,
  tot_cortados INTEGER, tot_recusados INTEGER, tot_procesados INTEGER,
  cerrado INTEGER NOT NULL DEFAULT 0,
  creado_en TEXT NOT NULL DEFAULT (datetime('now'))
);

CREATE TABLE IF NOT EXISTS corte_racimos_edad (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  corte_id INTEGER NOT NULL,
  edad_semanas INTEGER NOT NULL,
  color TEXT,
  calibre REAL,
  racimos INTEGER
);
CREATE INDEX IF NOT EXISTS idx_credad_corte ON corte_racimos_edad(corte_id);

CREATE TABLE IF NOT EXISTS corte_cajas_rel (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  corte_id INTEGER NOT NULL,
  finca TEXT, p_camion TEXT, contenedor TEXT, sello TEXT, cajas INTEGER
);
CREATE INDEX IF NOT EXISTS idx_ccajas_corte ON corte_cajas_rel(corte_id);

CREATE TABLE IF NOT EXISTS inspeccion_viajes (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  corte_id INTEGER NOT NULL,
  viaje INTEGER NOT NULL,
  lote_id INTEGER,
  cortados INTEGER, recusados INTEGER, procesados INTEGER
);
CREATE INDEX IF NOT EXISTS idx_iv_corte ON inspeccion_viajes(corte_id);

CREATE TABLE IF NOT EXISTS inspeccion_muestreo (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  corte_id INTEGER NOT NULL,
  lote_id INTEGER, edad INTEGER,
  peso REAL, calibre REAL, largo_2da REAL, largo_ultima REAL,
  n_manos INTEGER, calidad INTEGER, defecto TEXT
);
CREATE INDEX IF NOT EXISTS idx_im_corte ON inspeccion_muestreo(corte_id);

